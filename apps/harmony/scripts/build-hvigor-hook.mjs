#!/usr/bin/env node
/**
 * hvigor 构建钩子示例 —— 把 shared/messages/<locale>.json 注入到产物
 *
 * hvigor 5.x 支持 hook plugin 机制。本文件展示如何：
 *   1. 读 shared/messages/{en,zh-CN,zh-TW,ja}.json
 *   2. 合并成单一对象
 *   3. 序列化为 JS 字面量，写入 entry/src/main/ets/generated/messages.generated.ets
 *
 * hvigor 在 entry/build-profile.json5 中配置 hook 路径后会调用此脚本。
 * 当前骨架里只是示例，**实际集成需要在 hvigor plugin 中注册**。
 */

import { writeFileSync, mkdirSync, readFileSync, existsSync } from 'node:fs'
import { join, resolve } from 'node:path'

const REPO_ROOT = resolve(import.meta.dirname, '../../..')
const SHARED_MESSAGES = join(REPO_ROOT, 'shared/messages')
const OUT_DIR = resolve(import.meta.dirname, '../entry/src/main/ets/generated')
const OUT_FILE = join(OUT_DIR, 'messages.generated.ets')

const LOCALES = ['en', 'zh-CN', 'zh-TW', 'ja']

function main() {
  const bundle = {}
  for (const locale of LOCALES) {
    const file = join(SHARED_MESSAGES, `${locale}.json`)
    if (!existsSync(file)) {
      console.error(`[i18n] missing: ${file}`)
      process.exit(1)
    }
    bundle[locale] = JSON.parse(readFileSync(file, 'utf8'))
  }

  // 序列化为 ArkTS 字面量（ArkTS 是 TS 超集，可以直接放对象字面量）
  const jsonLiteral = JSON.stringify(bundle)

  mkdirSync(OUT_DIR, { recursive: true })

  const content = `// ⚠️ Auto-generated by scripts/build-hvigor-hook.mjs. Do not edit by hand.
// Source: shared/messages/{en,zh-CN,zh-TW,ja}.json
// Run: cd apps/harmony && node scripts/build-hvigor-hook.mjs

export const AAIGC_MESSAGES: Record<string, Record<string, unknown>> = ${jsonLiteral}
`

  writeFileSync(OUT_FILE, content, 'utf8')
  console.log(`[i18n] wrote ${OUT_FILE} (${LOCALES.length} locales)`)
}

main()